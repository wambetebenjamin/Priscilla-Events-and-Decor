#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Self-hosted fonts.
#
# The design source loads Roboto (body) and Raleway (headings and nav) from the
# Google Fonts CDN with display=swap and a fixed weight axis. Google Fonts is not
# reachable from the build sandbox and a third-party font request is not wanted in
# production either, so the same two upstream families are installed from the
# matching @fontsource packages and self-hosted out of /public/fonts.
#
# This script copies the woff2 files AND generates app/styles/fonts.css so that
# every @font-face rule states its own src, font-weight, font-style and
# font-display explicitly, with the exact unicode-range taken from the upstream
# package rather than retyped by hand.
# ---------------------------------------------------------------------------
set -euo pipefail
cd "$(dirname "$0")/.."

OUT_DIR="public/fonts"
CSS="app/styles/fonts.css"
mkdir -p "$OUT_DIR"

# family|css file basename|weights
FAMILIES=(
  "roboto|Roboto|300 400 500 700"
  "raleway|Raleway|300 400 500 600 700"
)
SUBSETS=("latin" "latin-ext")

cat > "$CSS" <<'HEADER'
/* ---------------------------------------------------------------------------
   Fonts for Priscilla Events and Decor.

   Source contract extracted from the design source (TheEvent, index.html lines 15-18):
     family=Roboto  weights 100,300,400,500,700,900 (+ italics), display=swap
     family=Raleway weights 100,200,300,400,500,600,700,800,900 (+ italics), display=swap
   Roboto is --default-font (body), Raleway is --heading-font and --nav-font.

   These rules are generated by scripts/copy-fonts.sh. Each one states src,
   font-weight, font-style and font-display explicitly and carries the upstream
   unicode-range so the browser only downloads the subsets it needs.
   --------------------------------------------------------------------------- */

HEADER

count=0
for entry in "${FAMILIES[@]}"; do
  IFS='|' read -r pkg family weights <<< "$entry"
  for subset in "${SUBSETS[@]}"; do
    for weight in $weights; do
      for style in normal italic; do
        srcfile="node_modules/@fontsource/${pkg}/files/${pkg}-${subset}-${weight}-${style}.woff2"
        [ -f "$srcfile" ] || continue
        dest="${pkg}-${subset}-${weight}-${style}.woff2"
        cp "$srcfile" "$OUT_DIR/$dest"

        # Pick the upstream stylesheet that declares this exact face. The normal
        # weights live in "${weight}.css" and the italics in "${weight}-italic.css".
        if [ "$style" = "italic" ]; then
          upstream_css="node_modules/@fontsource/${pkg}/${weight}-italic.css"
        else
          upstream_css="node_modules/@fontsource/${pkg}/${weight}.css"
        fi

        # Pull the unicode-range that the upstream package declares for this exact
        # subset, so the value is never invented. The @font-face block that mentions
        # this file is located with awk and the unicode-range read out of that block.
        range=$(awk -v f="${pkg}-${subset}-${weight}-${style}.woff2" '
                  index($0, f) { inblock = 1 }
                  inblock && /unicode-range/ { sub(/^[ \t]*/, ""); print; exit }
                ' "$upstream_css" 2>/dev/null || true)
        [ -n "$range" ] || range=""

        cat >> "$CSS" <<EOF
@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url('/fonts/${dest}') format('woff2');
  ${range}
}

EOF
        count=$((count+1))
      done
    done
  done
done

# Bootstrap Icons: the design source declares this rule with font-display: block and
# two sources (woff2 then woff). The only change is the path, because the files are
# served from /public/fonts instead of ./fonts. Everything else is verbatim.
ICON_CSS="node_modules/bootstrap-icons/font/bootstrap-icons.css"
if [ -f "$ICON_CSS" ]; then
  cp node_modules/bootstrap-icons/font/fonts/bootstrap-icons.woff2 "$OUT_DIR/" 2>/dev/null || true
  cp node_modules/bootstrap-icons/font/fonts/bootstrap-icons.woff  "$OUT_DIR/" 2>/dev/null || true
  # Keep the version query string from the source verbatim, e.g. ?dd67030699838ea613ee6dbda90effa6
  hash=$(sed -n 's/.*bootstrap-icons\.woff2\([^")]*\).*/\1/p' "$ICON_CSS" | head -1)
  cat >> "$CSS" <<EOF
/* Verbatim from the design source, assets/vendor/bootstrap-icons/bootstrap-icons.css.
   Only the two paths changed: ./fonts/ -> /fonts/ because the files are served
   from /public/fonts. font-display, family name, format order and version query
   are untouched. */
@font-face {
  font-display: block;
  font-family: "bootstrap-icons";
  src: url("/fonts/bootstrap-icons.woff2${hash}") format("woff2"),
url("/fonts/bootstrap-icons.woff${hash}") format("woff");
}
EOF
fi

echo "font files copied: $count"
ls -1 "$OUT_DIR" | head -5
echo "..."
du -sh "$OUT_DIR"
